<p>Easy Prayer ist eine progressive Web-App. Sie können die App im Browser verwenden oder auf Ihrem Mobilgerät installieren.</p>
<p>Die Gebetszeiten werden direkt auf Ihrem Gerät anhand des gewählten Standorts und der gewählten Berechnungsmethode ermittelt.</p>
<h4>Funktionen</h4>
<ul class="ul">
	<li>Übersichtliche Gebetszeiten</li>
	<li>Responsive Darstellung im Browser und auf Mobilgeräten</li>
	<li>Installierbar und offline nutzbar</li>
	<li>Automatische Standortermittlung</li>
	<li>Städtesuche und gespeicherte Städte</li>
	<li>Auswahl der Berechnungsmethode und der Asr-Rechtsschule</li>
	<li>Separate manuelle Zeitkorrekturen für jede Berechnungsmethode</li>
	<li>Wochen- und Monatsansicht</li>
	<li>Deutsch, Englisch und Türkisch</li>
	<li>Druckbar mit Strg+P</li>
</ul>
